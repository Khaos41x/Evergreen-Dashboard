import { chromium } from 'playwright-core'
import { mkdirSync } from 'node:fs'

const browser = await chromium.launch({ executablePath: 'C:\\Program Files (x86)\\Microsoft\\Edge\\Application\\msedge.exe', headless: true })
const page = await browser.newPage({ viewport: { width: 1440, height: 900 } })
await page.goto(process.argv[2] ?? 'http://127.0.0.1:4324/', { waitUntil: 'networkidle' })
await page.getByRole('button', { name: 'Abrir produtividade pessoal' }).click()
await page.evaluate(() => localStorage.clear())
await page.reload({ waitUntil: 'networkidle' })

const initialTimer = await page.locator('.hero-timer strong').textContent()
if (initialTimer !== '00:00') throw new Error(`Expected idle timer 00:00, received ${initialTimer}`)

await page.keyboard.press('Control+K')
if (!(await page.getByPlaceholder('Type a command or search…').isVisible())) throw new Error('Ctrl+K did not open the command palette')
await page.keyboard.press('Escape')
await page.keyboard.press('c')
if (!(await page.getByPlaceholder('Task title').isVisible())) throw new Error('C did not open New Task')
await page.getByRole('button', { name: 'Close new task' }).click()
await page.getByRole('button', { name: 'Home' }).click()

await page.locator('.new-project').click()
await page.getByPlaceholder('Project name').fill('Product launch')
await page.getByRole('button', { name: 'Create project' }).click()
if (!(await page.getByText('Product launch').isVisible())) throw new Error('Created project was not rendered')

await page.getByRole('button', { name: /Create objective/ }).click()
await page.getByPlaceholder('Objective title').fill('Ship first release')
await page.getByRole('button', { name: 'Create objective', exact: true }).last().click()
if (!(await page.getByText('Ship first release').isVisible())) throw new Error('Created objective was not rendered')

await page.getByRole('button', { name: /Add a task/ }).click()
if (!(await page.getByPlaceholder('Task title').isVisible())) throw new Error('Add task did not open the task dialog')
await page.getByPlaceholder('Task title').fill('Prepare launch checklist')
await page.getByPlaceholder('Add a description…').fill('Confirm the final release details.')
await page.getByRole('button', { name: /Todo/ }).click()
await page.getByRole('menuitem', { name: 'In Progress' }).click()
await page.getByRole('button', { name: 'Você', exact: true }).click()
await page.getByRole('menuitem', { name: 'Unassigned' }).click()
await page.getByRole('button', { name: /Unassigned/ }).click()
await page.getByRole('menuitem', { name: 'Você' }).click()
await page.getByRole('button', { name: /No project/ }).click()
await page.getByRole('menuitem', { name: 'Product launch' }).click()
await page.getByRole('button', { name: /Normal/ }).click()
await page.getByRole('menuitem', { name: 'High' }).click()
await page.getByRole('button', { name: /Due date/ }).click()
await page.getByRole('menuitem', { name: 'Tomorrow' }).click()
await page.getByRole('button', { name: /No objective/ }).click()
await page.getByRole('menuitem', { name: 'Ship first release' }).click()
await page.getByRole('button', { name: 'Add checklist' }).click()
const checklistInput = page.getByPlaceholder('Add item…')
for (const item of ['Review scope', 'Run checks', 'Publish notes']) { await checklistInput.fill(item); await checklistInput.press('Enter') }
await page.getByRole('button', { name: 'Mark complete' }).first().click()
await page.getByRole('button', { name: 'Create task' }).click()
if (!(await page.locator('.task-title', { hasText: 'Prepare launch checklist' }).first().isVisible())) throw new Error('Created task was not rendered')

await page.locator('.task-title', { hasText: 'Prepare launch checklist' }).first().click()
const titleEditor = page.getByLabel('Task title')
await titleEditor.fill('Prepare release checklist')
await page.locator('.properties-grid select').first().selectOption('todo')
await page.getByRole('button', { name: 'Start Focus' }).click()
await page.getByRole('button', { name: 'Stopwatch' }).click()
await page.getByRole('button', { name: 'Start', exact: true }).click()
await page.waitForTimeout(1250)
const runningTimer = await page.locator('.hero-timer strong').textContent()
if (runningTimer === '00:00') throw new Error('Stopwatch did not start')

const progressA = await page.locator('.hero-timer').evaluate(node => getComputedStyle(node).getPropertyValue('--timer-progress'))
await page.waitForTimeout(120)
const progressB = await page.locator('.hero-timer').evaluate(node => getComputedStyle(node).getPropertyValue('--timer-progress'))
if (!(await page.locator('.hero-timer').getAttribute('class')).includes('stopwatch')) throw new Error('Stopwatch should use an indeterminate indicator')

await page.getByRole('button', { name: 'Pause' }).click()
const pausedTimer = await page.locator('.hero-timer strong').textContent()
await page.waitForTimeout(1100)
if (await page.locator('.hero-timer strong').textContent() !== pausedTimer) throw new Error('Paused timer continued running')

await page.reload({ waitUntil: 'networkidle' })
if (await page.locator('.hero-timer strong').textContent() !== pausedTimer) throw new Error('Paused session did not survive reload')
await page.getByRole('button', { name: 'Resume' }).click()
await page.waitForTimeout(1100)
if (await page.locator('.hero-timer strong').textContent() === pausedTimer) throw new Error('Resume did not continue stopwatch')
await page.getByRole('button', { name: 'End session' }).click()
await page.getByRole('button', { name: 'End session' }).last().click()
await page.waitForFunction(() => document.querySelector('.hero-timer strong')?.textContent === '00:00')
if (await page.locator('.hero-timer strong').textContent() !== '00:00') throw new Error('Ending focus did not reset timer')

await page.getByRole('button', { name: 'Start focus' }).click()
await page.getByRole('button', { name: 'Timer' }).click()
await page.getByRole('button', { name: '25m' }).click()
await page.getByRole('button', { name: 'Start', exact: true }).click()
const countdownTimer = await page.locator('.hero-timer strong').textContent()
if (!['25:00', '24:59'].includes(countdownTimer ?? '')) throw new Error(`Timer mode did not start at 25 minutes: ${countdownTimer}`)
await page.getByRole('button', { name: 'End session' }).click()
await page.getByRole('button', { name: 'End session' }).last().click()

await page.reload({ waitUntil: 'networkidle' })
if (!(await page.getByText('Prepare release checklist').first().isVisible())) throw new Error('Task edits did not persist')

await page.evaluate(() => localStorage.setItem('evergreen.focus-session.v1', JSON.stringify({ mode: 'timer', status: 'running', startedAt: Date.now() - 61000, pausedAt: null, accumulatedPausedMs: 0, durationMs: 60000, title: 'Completion check', description: '' })))
await page.reload({ waitUntil: 'networkidle' })
if (!(await page.getByText('Session complete').isVisible())) throw new Error('Completed countdown did not open the completion flow')
await page.getByRole('button', { name: 'Deep' }).click()
await page.getByPlaceholder('Add a reflection…').fill('Finished cleanly')
await page.getByRole('button', { name: 'Save session' }).click()
if (!(await page.getByText('You finished a focus session').first().isVisible())) throw new Error('Completed session was not saved to Recent Work')

await page.getByRole('button', { name: 'Tasks', exact: true }).click()
await page.locator('.task-title', { hasText: 'Prepare release checklist' }).first().click()
await page.locator('.properties-grid select').first().selectOption('done')
await page.getByRole('complementary', { name: 'Task details' }).getByRole('button', { name: 'Close task' }).click()
await page.getByRole('tab', { name: 'Completed' }).click()
if (!(await page.locator('.task-title', { hasText: 'Prepare release checklist' }).first().isVisible())) throw new Error('Completed task was not moved to Completed')
await page.getByRole('button', { name: 'Home' }).click()

mkdirSync('output/playwright', { recursive: true })
await page.screenshot({ path: 'output/playwright/functional-home-1440x900.png', fullPage: true })
console.log(JSON.stringify({ initialTimer, runningTimer, pausedTimer, countdownTimer, stopwatchIndeterminate: true, ctrlK: true, taskCrud: true, taskCompletion: true, checklist: true, objective: true, project: true, persistence: true, sessionCompletion: true }))
await browser.close()
