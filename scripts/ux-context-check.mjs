import assert from 'node:assert/strict'
export async function checkContext({page,fixture,width,workspaceId}) {
 await page.locator('.os-company-directory article').first().getByRole('button',{name:'Entrar',exact:true}).click()
 const chip=page.locator('[data-current-company]')
 await page.waitForFunction(id=>document.querySelector('[data-current-company]')?.dataset.currentCompany===id,workspaceId)
 await chip.waitFor({timeout:3000})
 assert.equal(await chip.getAttribute('data-current-company'),workspaceId)
 await chip.getByRole('button',{name:/Seu acesso aqui/}).click()
 const popover=page.getByRole('region',{name:'Seu acesso aqui'})
 for(const label of ['Cargo exibido','Participação societária','Permissão operacional','Diretora QA','25%','A5 · Integrante QA'])await popover.getByText(label,{exact:true}).waitFor()
 await page.screenshot({path:'output/playwright/ux/after/context-'+width+'.png'})
 await chip.getByRole('button',{name:/Seu acesso aqui/}).click()
 const navigate=path=>page.evaluate(path=>{history.pushState(null,'',path);dispatchEvent(new PopStateEvent('popstate'))},path)
 for(const route of ['/economy','/founders','/hub']){
  await navigate(route); if(route==='/hub')await page.locator('.reference-hero').waitFor();else await page.getByRole('heading',{name:route==='/founders'?'O grupo, em perspectiva.':'Finanças',exact:true}).waitFor(); await chip.waitFor()
  assert.equal(await chip.getAttribute('data-current-company'),workspaceId)
 }
 await navigate('/founders')
 await page.getByRole('button',{name:'Governança',exact:true}).click()
 await page.getByRole('button',{name:'Conceder acesso Fundadores',exact:true}).click()
 await page.locator('select[name="user_id"]').selectOption('candidate-qa',{force:true})
 await page.getByRole('button',{name:'Salvar',exact:true}).click()
 const governance=page.getByRole('dialog',{name:'Revisar ação de governança'})
 await governance.getByText('Holding fixture',{exact:true}).waitFor()
 await governance.getByText(/Você age como:/).waitFor()
 await governance.getByRole('button',{name:'Conceder acesso Fundadores',exact:true}).waitFor()
 await governance.getByRole('button',{name:'Fechar diálogo'}).click()
 await navigate('/economy')
 await page.getByRole('button',{name:'Preparar transferência',exact:true}).click()
 await page.locator('input[name="cents"]').fill('125,40')
 await page.locator('input[name="description"]').fill('Revisão de escopo QA')
 await page.locator('select[name="to_account_id"]').selectOption('reserve-'+workspaceId,{force:true})
 await page.getByRole('button',{name:'Salvar registro',exact:true}).click()
 const review=page.getByRole('dialog',{name:'Confirmar transferência',exact:true})
 await review.getByText(new RegExp('Em:.*'+fixture.workspaces[0].name)).waitFor()
 await review.getByText(/Você age como:.*admin/).waitFor()
 await review.getByRole('button',{name:/Transferir.*125,40.*Reserva/}).waitFor()
 await review.getByRole('button',{name:'Voltar ao formulário',exact:true}).click()
 const other=fixture.workspaces.find(row=>row.id!==workspaceId)
 await chip.getByRole('button',{name:/Seu acesso aqui/}).click()
 page.once('dialog',dialog=>dialog.dismiss())
 await popover.getByRole('button',{name:'Abrir empresa '+other.name,exact:true}).click()
 assert.equal(await chip.getAttribute('data-current-company'),workspaceId)
 if(!await popover.isVisible())await chip.getByRole('button',{name:/Seu acesso aqui/}).click()
 page.once('dialog',dialog=>dialog.accept())
 await popover.getByRole('button',{name:'Abrir empresa '+other.name,exact:true}).click()
 await page.waitForFunction(id=>document.querySelector('[data-current-company]')?.dataset.currentCompany===id,other.id)
 assert.equal(await page.getByRole('dialog',{name:'Confirmar transferência',exact:true}).count(),0)
 await chip.getByRole('button',{name:/Seu acesso aqui/}).click()
 await popover.getByText('A6 · Convidado QA',{exact:true}).waitFor()
 console.log(JSON.stringify({item:'P0-2',width,checks:9,source:'respostas HTTP controladas; sem servidor hospedado'}))
 return {item:'P0-2',width,checks:9}
}
