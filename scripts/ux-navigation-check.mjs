import assert from 'node:assert/strict'
export async function checkNavigation({page,width,fixture}){
 await page.locator('.os-company-directory article').first().getByRole('button',{name:'Entrar',exact:true}).click()
 const sidebar=page.locator('#workspace-sidebar'),rail=page.getByRole('navigation',{name:'Empresas da holding'})
 await page.screenshot({path:'output/playwright/ux/'+(process.env.UX_RECORD==='1'?'before':'after')+'/navigation-'+width+'.png'})
 if(width>600&&width<=1000){
  assert.equal(await sidebar.isVisible(),true,'Barra contextual não está acessível sem drawer')
  assert.equal(await rail.isVisible(),true)
  const selected=await rail.locator('[aria-current="page"]').evaluate(element=>({weight:parseFloat(getComputedStyle(element).fontWeight),marker:getComputedStyle(element,'::before').content,width:parseFloat(getComputedStyle(element,'::before').width)}))
  assert.ok(selected.weight>=700&&selected.marker!=='none'&&selected.width>=3)
  assert.ok((await sidebar.boundingBox()).width<=72)
  await page.locator('.collab-main').hover()
  await page.keyboard.press('Control+Shift+\\')
  await sidebar.getByRole('button',{name:'Fixar barra contextual',exact:true}).waitFor()
  await sidebar.getByRole('button',{name:'Fixar barra contextual',exact:true}).click()
  assert.equal(await sidebar.getAttribute('data-pinned'),'true')
  await sidebar.getByRole('button',{name:'Recolher barra contextual',exact:true}).click()
  await rail.getByRole('button',{name:'Abrir empresa '+fixture.workspaces[1].name,exact:true}).click()
  await rail.getByRole('button',{name:'Abrir empresa '+fixture.workspaces[0].name,exact:true}).click()
  await sidebar.getByRole('button',{name:'Conversas',exact:true}).click()
  await page.locator('.conversation-directory').waitFor()
  await rail.getByRole('button',{name:'Abrir empresa '+fixture.workspaces[1].name,exact:true}).click()
  await rail.getByRole('button',{name:'Abrir empresa '+fixture.workspaces[0].name,exact:true}).click()
  await page.locator('.conversation-directory').waitFor()
  await rail.getByRole('button',{name:'Abrir empresa '+fixture.workspaces[1].name,exact:true}).click()
  await sidebar.getByRole('button',{name:'Finanças',exact:true}).click()
  await page.getByRole('heading',{name:'Finanças',exact:true}).waitFor()
  await rail.getByRole('button',{name:'Abrir empresa '+fixture.workspaces[0].name,exact:true}).click()
  await page.locator('.conversation-directory').waitFor()
  await rail.getByRole('button',{name:'Abrir empresa '+fixture.workspaces[1].name,exact:true}).click()
  await page.getByRole('heading',{name:'Finanças',exact:true}).waitFor()
  await rail.getByRole('button',{name:'Abrir empresa '+fixture.workspaces[0].name,exact:true}).click()
  await sidebar.locator('.workspace-channel-row small').getByText('3',{exact:true}).first().waitFor()
  await page.locator('.conversation-directory-list').getByRole('button').first().click()
  await page.locator('.collab-history').waitFor()
  // Switching: one rail click. Finding conversation: directory + row, two clicks.
  await rail.getByRole('button',{name:'Abrir empresa '+fixture.workspaces[0].name,exact:true}).focus()
  await page.keyboard.press('Tab')
  assert.equal(await page.evaluate(()=>document.activeElement?.tagName),'BUTTON')
 }else if(width<=600){
  assert.equal(await rail.isVisible(),false)
  const bottom=page.getByRole('navigation',{name:'Navegação mobile'})
  assert.ok(await bottom.getByRole('button').count()<=6)
  await bottom.getByRole('button',{name:'Mais',exact:true}).click()
  const more=page.getByRole('dialog',{name:'Mais destinos'})
  await more.getByRole('button',{name:'Finanças',exact:true}).click()
  await page.getByRole('heading',{name:'Finanças',exact:true}).waitFor()
  await bottom.getByRole('button',{name:'Mais',exact:true}).click()
  await more.getByRole('button',{name:'Fundadores',exact:true}).click()
  await page.getByRole('heading',{name:'O grupo, em perspectiva.',exact:true}).waitFor()
  await page.locator('[data-current-company]').waitFor()
 }
 return {item:'P1-3',width,checks:13}
}
