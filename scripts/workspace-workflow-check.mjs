// Tests the actual React components with an in-memory HTTP double.
// This does not authenticate a real user or prove Supabase/RLS behavior.
import assert from 'node:assert/strict'

export async function checkWorkspaceWorkflow({page, width, fixture, userId, workspaceId, otherWorkspaceId, go}) {
 const theme=await page.evaluate(()=>document.documentElement.dataset.theme)
 const capture=(name)=>'output/playwright/workflow-'+name+'-'+theme+'-'+width+'.png'
 const title='Preparar reunião da diretoria'
 const otherTitle='Revisar produto da segunda empresa'
 const noOverflow=async()=>assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth),false)
 const home=page.locator('.domain-home')
 async function chooseCompany(name) {
  await page.locator('[data-current-company]').getByRole('button',{name:/Seu acesso aqui/}).click()
  await page.getByRole('region',{name:'Seu acesso aqui'}).getByRole('button',{name:'Abrir empresa '+name,exact:true}).click()
  await page.waitForFunction(expected=>document.querySelector('.access-trigger strong')?.textContent===expected,name)
  if(!await home.isVisible())await go('Hoje')
 }
 async function saveTask(name) {
  const editor=page.getByRole('dialog',{name:'Nova tarefa',exact:true})
  await editor.getByLabel('Título',{exact:true}).fill(name)
  await editor.getByRole('textbox',{name:'Descrição',exact:true}).fill('Contexto registrado pela interface de teste.')
  await editor.getByRole('button',{name:'Salvar tarefa',exact:true}).click()
  await editor.waitFor({state:'hidden'})
 }

 await page.locator('.os-company-directory article').first().getByRole('button',{name:'Entrar',exact:true}).click()
 await home.waitFor()
 assert.equal(await page.locator('.access-trigger strong').isVisible(),true)
 await noOverflow()
 const hero=await home.locator('.reference-hero').boundingBox()
 const timer=await home.locator('.hero-timer').boundingBox()
 const action=await home.getByRole('button',{name:'Iniciar foco',exact:true}).boundingBox()
 assert.ok(hero.height>190&&timer.width>=112,'Keep the approved tree and large timer')
 assert.ok(action.x+action.width<=timer.x||action.y+action.height<=timer.y,'No overlapping controls')
 if(width>600) {
  assert.equal(await page.getByRole('navigation',{name:'Empresas da holding'}).isVisible(),true)
  const rail=page.getByRole('navigation',{name:'Empresas da holding'})
  assert.ok(await rail.getByRole('button',{name:/Abrir empresa/}).count()===2)
 }
 await home.getByRole('button',{name:'Adicionar tarefa',exact:true}).click()
 await saveTask(title)
 const saved=fixture.records.find(r=>r.title===title)
 assert.ok(saved&&saved.workspace_id===workspaceId&&saved.assignee_id===userId,'POST carries the current tenant and assignee')
 await go('Hoje')
 await home.getByRole('button').filter({hasText:'Prioridade atual'}).click()
 const editor=page.getByRole('dialog',{name:'Detalhes da tarefa',exact:true})
 assert.equal(await editor.getByLabel('Título',{exact:true}).inputValue(),title)
 await editor.getByRole('textbox',{name:'Descrição',exact:true}).fill('Descrição atualizada e relida.')
 await editor.getByRole('button',{name:'Salvar tarefa',exact:true}).click()
 await editor.waitFor({state:'hidden'})
 assert.equal(fixture.records.find(r=>r.id===saved.id).description,'Descrição atualizada e relida.')
 await home.getByRole('button').filter({hasText:'Próxima ação'}).click()
 assert.equal(await editor.getByRole('textbox',{name:'Descrição',exact:true}).inputValue(),'Descrição atualizada e relida.')
 await page.keyboard.press('Escape')
 await home.locator('.day-title').filter({hasText:title}).click()
 assert.equal(await editor.getByLabel('Título',{exact:true}).inputValue(),title)
 await page.keyboard.press('Escape')
 await go('Tarefas')
 assert.equal(await page.getByRole('dialog').count(),0,'Returning to Tasks must not repeat an old create request')

 // A failed write must leave the editor and content available for retry.
 await page.getByRole('button',{name:'Nova tarefa',exact:true}).click()
 const newEditor=page.getByRole('dialog',{name:'Nova tarefa',exact:true})
 await newEditor.getByLabel('Título',{exact:true}).fill('Repetir gravação após falha')
 fixture.failRecordOnce=true
 await newEditor.getByRole('button',{name:'Salvar tarefa',exact:true}).click()
 await newEditor.getByRole('alert').waitFor()
 assert.equal(await newEditor.getByLabel('Título',{exact:true}).inputValue(),'Repetir gravação após falha')
 await newEditor.getByRole('button',{name:'Salvar tarefa',exact:true}).click()
 await newEditor.waitFor({state:'hidden'})
 assert.equal(fixture.records.filter(r=>r.title==='Repetir gravação após falha').length,1)

 await go('Hoje')
 await home.locator('.day-title').filter({hasText:title}).click()
 page.once('dialog',dialog=>dialog.accept())
 await editor.getByRole('button',{name:'Focar nesta tarefa',exact:true}).click()
 const focusDialog=page.getByRole('dialog',{name:'Iniciar foco',exact:true})
 assert.equal(await focusDialog.getByLabel('Título',{exact:true}).inputValue(),title)
 await focusDialog.getByRole('button',{name:'Iniciar',exact:true}).click()
 await focusDialog.waitFor({state:'hidden'})
 await home.getByRole('button',{name:'Pausar',exact:true}).click()
 await home.getByRole('button',{name:'Retomar',exact:true}).waitFor()
 const paused=fixture.focus.find(f=>f.workspace_id===workspaceId&&f.status==='paused')
 assert.ok(paused?.started_at&&paused.paused_at)
 await home.getByRole('button',{name:'Retomar',exact:true}).click()
 await home.getByRole('button',{name:'Pausar',exact:true}).waitFor()
 const started=fixture.focus[0].started_at
 await page.goto('http://127.0.0.1:5187/output/playwright/fixture.html',{waitUntil:'domcontentloaded'})
 await page.locator('.os-company-directory article').first().getByRole('button',{name:'Entrar',exact:true}).click()
 await home.getByRole('button',{name:'Pausar',exact:true}).waitFor()
 assert.equal(fixture.focus[0].started_at,started,'A reload must reuse the server timestamp')
 await home.getByRole('button',{name:'Pausar',exact:true}).click()
 await home.getByRole('button',{name:'Retomar',exact:true}).waitFor()
 await page.screenshot({path:capture('today')})

 await go('Mensagens')
 const composer=page.getByRole('textbox',{name:'Mensagem',exact:true})
 await composer.fill('Mensagem registrada na primeira empresa')
 await composer.press('Enter')
 await page.getByText('Mensagem registrada na primeira empresa',{exact:true}).waitFor()
 assert.equal(fixture.messages[0].channel_id,fixture.channels[0].id)
 await page.screenshot({path:capture('chat')})

 await chooseCompany('Outra empresa QA')
 await home.getByText('Nenhuma prioridade definida',{exact:true}).waitFor()
 assert.equal(await home.locator('.day-title').count(),0)
 assert.equal(await home.getByRole('button',{name:'Iniciar foco',exact:true}).isVisible(),true,'Focus is scoped to the selected company')
 await home.getByRole('button',{name:'Adicionar tarefa',exact:true}).click()
 await saveTask(otherTitle)
 assert.equal(fixture.records.find(r=>r.title===otherTitle).workspace_id,otherWorkspaceId)
 await go('Hoje')
 await home.getByRole('button').filter({hasText:'Próxima ação'}).click()
 assert.equal(await editor.getByLabel('Título',{exact:true}).inputValue(),otherTitle)
 await page.keyboard.press('Escape')
 await go('Mensagens')
 await composer.waitFor()
 assert.equal(await page.getByText('Mensagem registrada na primeira empresa',{exact:true}).count(),0)
 assert.equal(await composer.inputValue(),'','A company change must not reuse the old channel draft')
 await composer.fill('Mensagem da segunda empresa')
 await composer.press('Enter')
 await page.getByText('Mensagem da segunda empresa',{exact:true}).waitFor()
 assert.equal(fixture.messages.find(m=>m.body==='Mensagem da segunda empresa').channel_id,fixture.channels[1].id)
 await noOverflow()

 await chooseCompany('UI fixture workspace')
 await home.locator('.day-title').filter({hasText:title}).waitFor()
 assert.equal(await home.locator('.day-title').filter({hasText:otherTitle}).count(),0)
 await home.getByRole('button',{name:'Retomar',exact:true}).waitFor()
 await go('Tarefas')
 await page.getByPlaceholder('Buscar tarefas...').fill(title)
 assert.equal(await page.locator('.domain-tasks .task-row').count(),1)
 await page.locator('.domain-tasks .task-title').filter({hasText:title}).click()
 assert.equal(await editor.getByRole('textbox',{name:'Descrição',exact:true}).inputValue(),'Descrição atualizada e relida.')
 await page.keyboard.press('Escape')
 await go('Hoje')
 await home.getByRole('button',{name:'Concluir Repetir gravação após falha',exact:true}).click()
 await page.waitForFunction(()=>!document.querySelector('.my-day-list')?.textContent.includes('Repetir gravação após falha'))
 assert.equal(fixture.records.find(r=>r.title==='Repetir gravação após falha').status,'done')
 await page.screenshot({path:capture('final')})
 await noOverflow()
 return {width,theme,homeCompletionSaved:true,approvedRailAndHero:true,visibleCompanyContext:true,taskCreateReadUpdate:true,homeOpensSpecificTask:true,createRequestConsumed:true,failedWriteRetriedOnce:true,focusStartPauseResumeReload:true,companyTaskAndFocusIsolation:true,channelIsolation:true,taskSearch:true,noOverflow:true,evidence:'React UI + HTTP doubles; no real authentication, Supabase persistence, RLS or Realtime'}
}
